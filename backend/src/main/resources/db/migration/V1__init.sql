-- ---------- Katalog ----------
CREATE TABLE shop_products (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255)  NOT NULL,
    sku          VARCHAR(64)   NOT NULL,
    price        NUMERIC(19,2) NOT NULL CHECK (price > 0),
    stock        INTEGER       NOT NULL CHECK (stock >= 0),
    weight_gram  INTEGER       NOT NULL CHECK (weight_gram > 0),
    category     VARCHAR(255),
    image_url    VARCHAR(1024),
    description  VARCHAR(4000),
    active       BOOLEAN       NOT NULL DEFAULT TRUE,
    version      BIGINT,
    created_at   TIMESTAMP(6) WITH TIME ZONE,
    updated_at   TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_products_sku UNIQUE (sku)
);
CREATE INDEX idx_product_category ON shop_products (category);
CREATE INDEX idx_product_active ON shop_products (active);

-- ---------- Order ----------
CREATE TABLE shop_orders (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number      VARCHAR(40)   NOT NULL,
    customer_name     VARCHAR(255)  NOT NULL,
    customer_email    VARCHAR(255)  NOT NULL,
    customer_phone    VARCHAR(32)   NOT NULL,
    address           VARCHAR(1000) NOT NULL,
    city              VARCHAR(255)  NOT NULL,
    postal_code       VARCHAR(10)   NOT NULL,
    notes             VARCHAR(500),
    status            VARCHAR(32)   NOT NULL CHECK (status IN
                        ('PENDING_PAYMENT','PAID','PROCESSING','SHIPPED','DELIVERED','CANCELLED','REFUNDED')),
    subtotal          NUMERIC(19,2) NOT NULL,
    shipping_fee      NUMERIC(19,2) NOT NULL,
    total             NUMERIC(19,2) NOT NULL,
    total_weight_gram INTEGER,
    courier           VARCHAR(255),
    courier_service   VARCHAR(255),
    shipping_etd      VARCHAR(255),
    tracking_number   VARCHAR(255),
    created_at        TIMESTAMP(6) WITH TIME ZONE,
    updated_at        TIMESTAMP(6) WITH TIME ZONE,
    expires_at        TIMESTAMP(6) WITH TIME ZONE,
    paid_at           TIMESTAMP(6) WITH TIME ZONE,
    shipped_at        TIMESTAMP(6) WITH TIME ZONE,
    delivered_at      TIMESTAMP(6) WITH TIME ZONE,
    cancelled_at      TIMESTAMP(6) WITH TIME ZONE,
    version           BIGINT,
    CONSTRAINT uk_orders_number UNIQUE (order_number)
);
CREATE INDEX idx_order_status ON shop_orders (status);
CREATE INDEX idx_order_email ON shop_orders (customer_email);
CREATE INDEX idx_order_status_expires ON shop_orders (status, expires_at);
CREATE INDEX idx_order_paid_at ON shop_orders (paid_at);
CREATE INDEX idx_order_created_at ON shop_orders (created_at);

CREATE TABLE shop_order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT        NOT NULL REFERENCES shop_orders (id),
    product_id   BIGINT        NOT NULL REFERENCES shop_products (id),
    product_name VARCHAR(255)  NOT NULL,
    sku          VARCHAR(64)   NOT NULL,
    quantity     INTEGER       NOT NULL CHECK (quantity > 0),
    unit_price   NUMERIC(19,2) NOT NULL,
    line_total   NUMERIC(19,2) NOT NULL
);
CREATE INDEX idx_order_items_order ON shop_order_items (order_id);
CREATE INDEX idx_order_items_product ON shop_order_items (product_id);

CREATE TABLE shop_order_status_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT       NOT NULL REFERENCES shop_orders (id),
    status     VARCHAR(32)  NOT NULL CHECK (status IN
                 ('PENDING_PAYMENT','PAID','PROCESSING','SHIPPED','DELIVERED','CANCELLED','REFUNDED')),
    note       VARCHAR(500),
    actor      VARCHAR(80),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_order_history_order ON shop_order_status_history (order_id);

-- ---------- Payment ----------
CREATE TABLE shop_payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT        NOT NULL REFERENCES shop_orders (id),
    provider        VARCHAR(32)   NOT NULL,
    transaction_id  VARCHAR(255),
    payment_type    VARCHAR(255),
    snap_token      VARCHAR(255),
    redirect_url    VARCHAR(1024),
    provider_status VARCHAR(255),
    amount          NUMERIC(19,2) NOT NULL,
    status          VARCHAR(16)   NOT NULL CHECK (status IN ('PENDING','PAID','FAILED','EXPIRED')),
    paid_at         TIMESTAMP(6) WITH TIME ZONE,
    created_at      TIMESTAMP(6) WITH TIME ZONE,
    updated_at      TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_payments_order UNIQUE (order_id)
);

-- ---------- Admin ----------
CREATE TABLE admin_users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            VARCHAR(50)  NOT NULL,
    display_name        VARCHAR(120) NOT NULL,
    password_hash       VARCHAR(100) NOT NULL,
    role                VARCHAR(16)  NOT NULL CHECK (role IN ('OWNER','STAFF')),
    active              BOOLEAN      NOT NULL DEFAULT TRUE,
    failed_attempts     INTEGER      NOT NULL DEFAULT 0,
    locked_until        TIMESTAMP(6) WITH TIME ZONE,
    last_login_at       TIMESTAMP(6) WITH TIME ZONE,
    password_changed_at TIMESTAMP(6) WITH TIME ZONE,
    created_at          TIMESTAMP(6) WITH TIME ZONE,
    updated_at          TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_admin_users_username UNIQUE (username)
);

CREATE TABLE admin_sessions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64)  NOT NULL,
    user_id    BIGINT       NOT NULL REFERENCES admin_users (id),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ip_address VARCHAR(64),
    user_agent VARCHAR(255),
    CONSTRAINT uk_admin_sessions_token UNIQUE (token_hash)
);
CREATE INDEX idx_admin_sessions_user ON admin_sessions (user_id);
CREATE INDEX idx_admin_sessions_expires ON admin_sessions (expires_at);
